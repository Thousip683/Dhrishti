"""Export stable OpenAPI, frontend types and development fixtures.

Run from the project root. --check fails instead of updating stale artifacts.
No Node runtime or model credentials are needed for this Stage 0 build step.
"""
import argparse
from datetime import datetime, timezone
import itertools
import json
from pathlib import Path
import sys
from unittest.mock import patch
from uuid import UUID

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from carbon_coach.api import app
from carbon_coach import domain as d, schemas as s

def ts_type(schema):
    if '$ref' in schema:
        return schema['$ref'].split('/')[-1]
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(v) for v in schema['enum'])
    for key in ('anyOf', 'oneOf'):
        if key in schema:
            return '(' + ' | '.join(ts_type(v) for v in schema[key]) + ')'
    kind = schema.get('type')
    if kind == 'null':
        return 'null'
    if kind in ('integer', 'number'):
        return 'number'
    if kind == 'boolean':
        return 'boolean'
    if kind == 'string':
        return 'string'
    if kind == 'array':
        return f'Array<{ts_type(schema.get("items", {}))}>'
    if kind == 'object' or 'properties' in schema:
        required = schema.get('required', [])
        props = [f'{json.dumps(k)}{"" if k in required else "?"}: {ts_type(v)};' for k,v in schema.get('properties', {}).items()]
        additional = schema.get('additionalProperties')
        if isinstance(additional, dict):
            props.append(f'[key: string]: {ts_type(additional)};')
        return '{ ' + ' '.join(props) + ' }' if props else 'Record<string, unknown>'
    return 'unknown'

class FixedClock(datetime):
    @classmethod
    def now(cls, tz=None):
        result = cls(2026, 10, 30, 10, 0, 0, tzinfo=timezone.utc)
        return result.astimezone(tz) if tz else result.replace(tzinfo=None)

def fixtures():
    sequence = itertools.count(1)
    with patch.object(d, 'uuid4', side_effect=lambda: UUID(int=next(sequence))), patch.object(d, 'datetime', FixedClock):
        ledger = {'timezone':'Asia/Kolkata','activities':[], 'calculations':{}}
        calculation = d.calculate(ledger,'travel',{'mode':'bus','distance_km':'12'})
        activity = d.log(ledger,calculation['id'],'2026-10-30')
        wrap = {'request_id':'fixture-request','status':'success'}
        result = {
            '_meta': {'mock':True, 'description':'Deterministic development fixtures; not a real user session.'},
            'calculation': s.CalculationResponse(**wrap, calculation=calculation).model_dump(mode='json'),
            'activity': s.ActivityResponse(**wrap, activity=activity).model_dump(mode='json'),
            'populated_summary': s.SummaryResponse(**wrap, summary=d.summary(ledger,'today')).model_dump(mode='json'),
            'empty_summary': s.SummaryResponse(**wrap, summary=d.summary({'timezone':'Asia/Kolkata'},'today')).model_dump(mode='json'),
            'empty_reductions': s.ReductionResponse(**wrap,**d.reductions(ledger)).model_dump(mode='json'),
            'capabilities': s.CapabilitiesResponse(**wrap,**d.capabilities(ledger)).model_dump(mode='json'),
            'validation_error': s.ErrorResponse(request_id='fixture-error', error=s.ErrorDetail(code='INVALID_REQUEST',message='Provide a distance in km.',retryable=False,field_errors=[s.FieldError(field='input.distance_km',reason='required')])).model_dump(mode='json'),
        }
    return result

def artifacts():
    schema = app.openapi()
    types = ['// Generated by scripts/export_contract.py. Do not edit by hand.', '// Decimal amounts, dates and timestamps remain strings.']
    for name, value in sorted(schema['components']['schemas'].items()):
        types.append(f'export type {name} = {ts_type(value)};')
    return {
        ROOT/'docs/openapi.json': json.dumps(schema,indent=2,sort_keys=True)+'\n',
        ROOT/'frontend/src/api/schema.d.ts': '\n\n'.join(types)+'\n',
        ROOT/'frontend/src/fixtures/application.json': json.dumps(fixtures(),indent=2,sort_keys=True)+'\n',
    }

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    args = parser.parse_args()
    stale=[]
    for path, content in artifacts().items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_text(content,encoding='utf-8')
            print(path.relative_to(ROOT))
    if stale:
        print('Contract artifacts are stale: '+', '.join(stale))
        sys.exit(1)
